#!/usr/bin/env python3
"""Gzip the device web pages into PROGMEM C arrays (run from this folder)."""
import gzip
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
INO = HERE / "MyAthan_OTA.ino"
OUT = HERE / "web_pages_gz.h"


def extract(name: str, text: str) -> bytes:
    m = re.search(
        r"const char " + name + r"\[\] PROGMEM = R\"=====\((.*?)\)=====\";",
        text,
        re.S,
    )
    if not m:
        raise SystemExit(f"could not find {name} in {INO.name}")
    return m.group(1).encode("utf-8")


def c_array(symbol: str, data: bytes) -> str:
    lines = [f"const uint8_t {symbol}[] PROGMEM = {{"]
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i : i + 16])
        lines.append(f"  {chunk},")
    lines.append("};")
    lines.append(f"const size_t {symbol}_LEN = {len(data)};")
    return "\n".join(lines)


def main() -> None:
    text = INO.read_text(encoding="utf-8")
    # Pages may live in the .ino (first pack) or as sidecar HTML files.
    control_html = HERE / "control.html"
    setup_html = HERE / "setup.html"
    if control_html.exists():
        control = control_html.read_bytes()
    else:
        control = extract("CONTROL_PAGE", text)
        control_html.write_bytes(control)
    if setup_html.exists():
        setup = setup_html.read_bytes()
    else:
        setup = extract("SETUP_PAGE", text)
        setup_html.write_bytes(setup)

    control_gz = gzip.compress(control, compresslevel=9, mtime=0)
    setup_gz = gzip.compress(setup, compresslevel=9, mtime=0)
    print(f"control.html {len(control)} -> gzip {len(control_gz)}")
    print(f"setup.html   {len(setup)} -> gzip {len(setup_gz)}")

    body = "\n".join(
        [
            "// Generated by pack_web.py — do not edit by hand.",
            "#pragma once",
            "#include <Arduino.h>",
            "",
            c_array("CONTROL_HTML_GZ", control_gz),
            "",
            c_array("SETUP_HTML_GZ", setup_gz),
            "",
        ]
    )
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT.name} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
